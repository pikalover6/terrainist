/** Translate a built building into Terrarium world space. */
function shiftBuilding(b: BuiltBuilding, dx: number, dz: number): BuiltBuilding {
  const rect = (r: { x0: number; z0: number; x1: number; z1: number }) => ({
    x0: r.x0 + dx,
    z0: r.z0 + dz,
    x1: r.x1 + dx,
    z1: r.z1 + dz,
  });
  const cells = (set: ReadonlySet<string>): Set<string> => {
    const out = new Set<string>();
    for (const key of set) {
      const comma = key.indexOf(",");
      out.add(`${Number(key.slice(0, comma)) + dx},${Number(key.slice(comma + 1)) + dz}`);
    }
    return out;
  };
  return {
    ...b,
    footprint: rect(b.footprint),
    interior: rect(b.interior),
    cells: cells(b.cells),
    ...(b.interiorCells === undefined ? {} : { interiorCells: cells(b.interiorCells) }),
    ...(b.basementInterior === undefined ? {} : { basementInterior: rect(b.basementInterior) }),
    ...(b.basementCells === undefined ? {} : { basementCells: cells(b.basementCells) }),
  };
}

