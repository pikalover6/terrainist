/**
 * The **Terrarium** — the human-review world. One exhibit, one platform, one
 * verdict.
 *
 * The dev world is a *contact sheet*: every exhibit the grammar can produce,
 * laid out edge to edge on one plain, so a build can be diffed against the one
 * before it by eye. That is the right shape for spotting a regression and the
 * wrong shape for collecting an opinion. Standing in it, a reviewer sees nine
 * buildings at once, has no way to say which one the note is about, and no way
 * to get the note out of the game at all.
 *
 * The Terrarium is the same registry — literally the same cells, read from
 * {@link planDevGrid} and {@link planPropExhibits} — rearranged around the act
 * of reviewing. Each exhibit gets a **station**: a platform floating in the
 * void with exactly one structure on it, so there is nothing else in frame to
 * confuse the judgement, and a small bank of machinery that makes the review
 * loop a thing you can do with your hands:
 *
 * - a **pressure plate** at the spot you arrive on, sitting on a command block
 *   that `say`s `>> STATION <id>`. That line lands in the client log, and it is
 *   what lets everything said afterwards be attributed to *this* exhibit;
 * - two **travel cubes** — 3x3x3 volumes of air, one on either side of the
 *   landing, that teleport whoever flies into them to the next or the previous
 *   station, wrapping at both ends, so the whole set can be walked without a
 *   map;
 * - **signs** naming the station and its parameters, so the thing you are
 *   looking at is identified in the world and not only in a manifest.
 *
 * ## v3: spectator flight, and no buttons at all
 *
 * v1 and v2 asked the reviewer to *press* things: NEXT/PREV to move, PASS/FAIL
 * to record a verdict. A real session (Kai, 2026-07-30) showed both to be in
 * the way. A reviewer who is judging how a building *looks* wants to be in
 * spectator mode — through walls, through roofs, no fall damage, no
 * accidentally-broken exhibit — and a spectator cannot press a button or step
 * on a plate. And a verdict is a sentence, not a pair of buttons: it is typed
 * in chat like every other note, and the harvester already reads it there.
 *
 * So v3 deletes the button wall entirely and replaces it with a mechanism a
 * spectator *can* trigger: a fly-into region. Beside each landing sit two
 * marked pads — **lime** for NEXT, **red** for PREV — each with a repeating
 * command block buried under it testing `execute if entity @a[<the cube>]`,
 * and two conditional chain blocks behind it doing the teleport and then the
 * `say >> STATION <destination>` that the harvester joins notes on. The player
 * leaves the region in the same tick they are teleported out of it, so the
 * chain fires exactly once per entry.
 *
 * The world's default game mode is **spectator** (`GameType 3`), set once in
 * `level.dat` rather than enforced by a repeating `gamemode` command: a
 * reviewer who wants to drop into creative for a screenshot must be able to,
 * and a rig that fought that toggle every tick would be unusable.
 *
 * Nothing here talks to a model, and nothing here reads the clock: the
 * Terrarium is generated by pure code from the pinned seed, so re-running it
 * after a grammar change produces the same stations in the same places and the
 * previous session's notes still join.
 *
 * ## v2: the multi-structure stations
 *
 * A single-structure station is the right shape for judging a *generator* and
 * the wrong shape for judging the *pipeline*. Nothing above can be asked "does
 * the lane meet the door?", "does the tunnel connect the cellars?", "does a
 * plaza with four buildings read as a place?" — those are compositions, and the
 * only honest way to exhibit one is to compile one.
 *
 * So after the single-structure grid comes a band of **multi-structure
 * stations**, each owning a real settlement-profile mini-document that goes
 * through {@link compileTerrain} and is then transplanted onto its platform.
 * See `terrarium-stations.ts` for the documents and for why transplanting beats
 * stitching separate worlds. They carry exactly the same machinery — arrival
 * plate, NEXT/PREV, PASS/FAIL, signs — because the review loop must not change
 * shape halfway through the walk.
 *
 * ## Why this file writes its own chunks
 *
 * Every other world in this compiler is materialized by {@link emitTerrain},
 * which fills every column of its region from bedrock up. That is exactly
 * wrong here: the point of a station is that the exhibit stands alone against
 * sky on every side, and a shared plain is precisely the confound the Terrarium
 * exists to remove. So it keeps a column plan — the generators need one, and
 * the harbour props need a pond dug into one — but materializes only the
 * columns inside a platform, and only down to {@link TERRARIUM_PLATFORM_FLOOR}.
 * Everything else is void. A multi-station's columns come from its own
 * compiled plan instead, through the same bounded, floored writer.
 */

