/** Which way a travel cube goes. */
export type TerrariumCubeDirection = "next" | "prev";

/** A box of world blocks, inclusive on every axis. */
export interface TerrariumBox {
  readonly x0: number;
  readonly y0: number;
  readonly z0: number;
  readonly x1: number;
  readonly y1: number;
  readonly z1: number;
}

/**
 * One travel cube: the region you fly into, the pad that marks it, and the
 * three command blocks buried under the pad that do the work.
 */
export interface TerrariumCube {
  readonly direction: TerrariumCubeDirection;
  /** The station this cube teleports to. */
  readonly target: string;
  /** The 3x3x3 volume of air a player has to enter. */
  readonly region: TerrariumBox;
  /** The marked 3x3 of pad blocks under it, at the platform surface. */
  readonly pad: TerrariumRect;
  /** The block name of the pad, and of its centre column. */
  readonly padBlock: string;
  readonly eyeBlock: string;
  /** The repeating detector's command — success powers the chain behind it. */
  readonly detect: string;
  /** Chain 1: the teleport. */
  readonly teleport: string;
  /** Chain 2: the marker line the harvester joins notes on. */
  readonly marker: string;
  /** Where the three command blocks sit, in chain order. */
  readonly blocks: readonly {
    readonly role: "detect" | "teleport" | "marker";
    readonly x: number;
    readonly y: number;
    readonly z: number;
  }[];
}

/** The machinery a station carries, as blocks and compounds. */
interface Machinery {
  readonly blocks: readonly StructureBlock[];
  readonly entities: readonly BlockEntity[];
}

/**
 * The two travel cubes a station carries, west (PREV) first then east (NEXT).
 *
 * Exported because the manifest↔world test asserts on exactly these strings and
 * these coordinates: the property that matters is that the command block buried
 * on the platform runs the command the manifest says it does, and a test that
 * rebuilt the string from its own template would only be checking itself.
 *
 * The selector appears three times — once to ask whether anyone is standing in
 * the cube, once to move them, once implicitly by the chain being conditional
 * on that move — and is written out identically each time on purpose: a
 * detector and a teleporter that disagree about the region would teleport
 * someone who was never in it.
 */
export function terrariumCubes(
  station: TerrariumStation,
  byId: ReadonlyMap<string, TerrariumStation>,
): TerrariumCube[] {
  const y = TERRARIUM_GROUND_Y;
  const zc = station.landing.z;
  const half = TERRARIUM_CUBE_SIZE >> 1;
  const make = (direction: TerrariumCubeDirection, target: string): TerrariumCube => {
    const cx = station.landing.x + (direction === "next" ? TERRARIUM_CUBE_OFFSET : -TERRARIUM_CUBE_OFFSET);
    const x0 = cx - half;
    const z0 = zc - half;
    const x1 = x0 + TERRARIUM_CUBE_SIZE - 1;
    const z1 = z0 + TERRARIUM_CUBE_SIZE - 1;
    // `dx=2` spans three columns, not two: the volume runs from `x` to
    // `x + dx + 1` exclusive. Getting this wrong makes a cube you can fly
    // through the far edge of without being seen.
    const span = TERRARIUM_CUBE_SIZE - 1;
    const selector = `@a[x=${x0},y=${y + 1},z=${z0},dx=${span},dy=${span},dz=${span}]`;
    const landing = (byId.get(target) as TerrariumStation).landing.tp;
    return {
      direction,
      target,
      region: { x0, y0: y + 1, z0, x1, y1: y + TERRARIUM_CUBE_SIZE, z1 },
      pad: { x0, z0, x1, z1, y },
      padBlock: TERRARIUM_CUBE_PADS[direction] as string,
      eyeBlock: TERRARIUM_CUBE_EYES[direction] as string,
      detect: `execute if entity ${selector}`,
      teleport: `tp ${selector} ${landing}`,
      marker: terrariumArrivalCommand(byId.get(target) as TerrariumStation),
      blocks: [
        { role: "detect", x: x0, y: y - 1, z: zc },
        { role: "teleport", x: x0 + 1, y: y - 1, z: zc },
        { role: "marker", x: x0 + 2, y: y - 1, z: zc },
      ],
    };
  };
  return [make("prev", station.prev), make("next", station.next)];
}

/** The command the arrival plate's command block runs. */
export function terrariumArrivalCommand(station: TerrariumStation): string {
  return `say >> STATION ${station.id}`;
}

/**
 * The two label signs a station carries, as their four lines each.
 *
 * One says what the station *is* — its id and its place in the registry — and
 * one says what the generator was *told*, which is the pair a reviewer needs
 * to turn "this roof is wrong" into a reproducible complaint.
 *
 * A multi-station's second sign says the *question* instead of the parameters.
 * There is no single generator config to quote — the provenance is a whole
 * document, which is in the manifest and cannot fit on a sign — and a reviewer
 * standing in front of a compiled hamlet needs to be told which of the dozen
 * things in frame the verdict is about.
 */
export function terrariumSignLines(station: TerrariumStation): [string[], string[]] {
  const p = station.provenance;
  if (station.kind === "spawn") {
    return [
      ["TERRARIUM", "", "fly into LIME", "to go forward"],
      ["RED goes back", "", "type in chat to", "leave a note"],
    ];
  }
  const multi = station.multi;
  if (multi !== undefined) {
    return [
      [`#${station.index + 1} ${multi.kind}`, truncate(multi.title, 15), multi.document, `seed ${multi.worldSeed}`],
      ["JUDGE THIS:", ...wrapSign(multi.question, 3)],
    ];
  }
  const size = `${p.size[0]}x${p.size[1]}x${p.size[2]}`;
  const extras = Object.keys(p.params ?? {}).join(" ");
  return [
    [`#${station.index + 1} ${p.row}`, truncate(station.id, 15), p.family, `col ${p.column}`],
    [
      `size ${size}`,
      p.roof === undefined ? `theme ${p.theme ?? "-"}` : `roof ${p.roof} f${p.floors ?? 1}`,
      p.roof === undefined ? extras : `theme ${p.theme ?? "-"}`,
      p.seedSalt === undefined ? extras : `salt ${p.seedSalt}`,
    ],
  ];
}

/** The four instruction signs on the spawn platform. */
const TERRARIUM_INSTRUCTIONS: readonly (readonly string[])[] = Object.freeze([
  ["HOW THIS WORKS", "1. fly into the", "   LIME pad to", "   go forward"],
  ["2. RED pad goes", "   back one", "3. look at the", "   one exhibit"],
  ["4. say anything", "in chat, verdict", "included: it is", "recorded here"],
  ["you are a", "spectator: fly", "through walls,", "touch nothing"],
]);

function truncate(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max - 1)}~`;
}

/**
 * Break a sentence across a fixed number of sign lines.
 *
 * Greedy, on word boundaries, at the fifteen characters a sign renders before
 * it starts eliding — and always exactly `lines` entries, because a sign
 * compound with three lines where four were expected renders the missing one
 * as the literal string `null` in game.
 */
function wrapSign(text: string, lines: number): string[] {
  const out: string[] = [];
  let current = "";
  for (const word of text.split(/\s+/)) {
    const candidate = current === "" ? word : `${current} ${word}`;
    if (candidate.length <= 15 || current === "") {
      current = candidate;
      continue;
    }
    out.push(current);
    current = word;
  }
  if (current !== "") out.push(current);
  while (out.length < lines) out.push("");
  return out.slice(0, lines);
}

/**
 * Build one station's machinery.
 *
 * The geometry is fixed relative to the landing spot, which is what makes the
 * rig navigable: the signs are always at the same two offsets, the lime pad is
 * always six columns east and the red one always six columns west, and a
 * reviewer who has done one station has done all of them.
 */
function buildMachinery(
  station: TerrariumStation,
  cubes: readonly TerrariumCube[],
  stack: PrismarineStack,
): Machinery {
  const blocks: StructureBlock[] = [];
  const entities: BlockEntity[] = [];
  const y = TERRARIUM_GROUND_Y;
  const state = (name: string, props?: Record<string, string>): number =>
    (props === undefined ? stack.blockByName(name)?.stateId : stack.blockStateOf(name, props)) ?? 0;

  const cx = station.landing.x;
  const zLand = station.landing.z;

  // --- the arrival plate, on its command block ------------------------------
  // The plate strongly powers the block beneath it, so an impulse command
  // block directly under the landing spot fires once per arrival — which is
  // exactly the granularity the log harvester wants.
  blocks.push({ x: cx, y, z: zLand, stateId: state("command_block", { conditional: "false", facing: "up" }) });
  blocks.push({
    x: cx,
    y: y + 1,
    z: zLand,
    stateId: state("stone_pressure_plate", { powered: "false" }),
  });
  entities.push(
    commandBlockEntity(cx, y, zLand, terrariumArrivalCommand(station), {
      auto: false,
      trackOutput: false,
      customName: "@",
    }),
  );

  // --- the label signs -----------------------------------------------------
  // Standing signs on the platform, one either side of the plate, facing south
  // so they read from the spot the player lands on.
  const [lineA, lineB] = terrariumSignLines(station);
  const signState = state("oak_sign", { rotation: "0", waterlogged: "false" });
  for (const [dx, lines] of [
    [-2, lineA],
    [2, lineB],
  ] as const) {
    blocks.push({ x: cx + dx, y: y + 1, z: zLand - 1, stateId: signState });
    entities.push(signEntity(cx + dx, y + 1, zLand - 1, { front: lines, waxed: true }));
  }

  // --- the spawn platform's instructions -----------------------------------
  if (station.kind === "spawn") {
    for (const [i, lines] of TERRARIUM_INSTRUCTIONS.entries()) {
      const x = cx - 3 + i * 2;
      blocks.push({ x, y: y + 1, z: zLand - 3, stateId: signState });
      entities.push(signEntity(x, y + 1, zLand - 3, { front: lines, waxed: true }));
    }
  }

  // --- the travel cubes ----------------------------------------------------
  // A marked 3x3 pad at the platform surface, the 3x3x3 of air above it left
  // alone, and the chain buried one course under the pad where it cannot be
  // seen, stood on, or broken. The chain runs west to east: the repeating
  // detector faces east into the first conditional chain block, which faces
  // east into the second — so a chain block only runs when the block behind it
  // succeeded, which is what makes "teleport, then announce" one atomic thing.
  for (const cube of cubes) {
    for (let x = cube.pad.x0; x <= cube.pad.x1; x++) {
      for (let z = cube.pad.z0; z <= cube.pad.z1; z++) {
        const eye = x === cube.pad.x0 + 1 && z === cube.pad.z0 + 1;
        blocks.push({
          x,
          y,
          z,
          stateId: eye ? state(cube.eyeBlock, { facing: "north" }) : state(cube.padBlock),
        });
      }
    }
    // Air, explicitly: the substrate put a surface block at `y` and nothing
    // above it, but a prop or a snow layer could have reached in, and a cube
    // with a block in it is a cube a creative-mode reviewer bounces off.
    for (let dy = 0; dy < TERRARIUM_CUBE_SIZE; dy++) {
      for (let x = cube.region.x0; x <= cube.region.x1; x++) {
        for (let z = cube.region.z0; z <= cube.region.z1; z++) {
          blocks.push({ x, y: y + 1 + dy, z, stateId: state("air") });
        }
      }
    }
    const commands: Record<string, string> = {
      detect: cube.detect,
      teleport: cube.teleport,
      marker: cube.marker,
    };
    for (const slot of cube.blocks) {
      const name = slot.role === "detect" ? "repeating_command_block" : "chain_command_block";
      blocks.push({
        x: slot.x,
        y: slot.y,
        z: slot.z,
        stateId: state(name, {
          conditional: slot.role === "detect" ? "false" : "true",
          facing: "east",
        }),
      });
      entities.push(
        // `auto` — "always active" — rather than redstone-powered: there is no
        // redstone down here, and a detector that needs a button defeats the
        // point of a mechanism a spectator can trigger.
        commandBlockEntity(slot.x, slot.y, slot.z, commands[slot.role] as string, {
          auto: true,
          trackOutput: false,
          customName: "@",
        }),
      );
    }
  }

  return { blocks, entities };
}

