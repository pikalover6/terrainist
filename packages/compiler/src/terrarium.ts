/**
 * One structure inside a multi-station's settlement.
 *
 * The point of the list is joinability: a reviewer's "the inn's roof is wrong"
 * has to reach the node that produced the inn, and the only durable handle on
 * that node is its path in the mini-document. Attribution is still recorded per
 * *station* — the harvester has no way to tell which of five buildings a chat
 * line was about — so this is what a human (or a later pass) reads to turn one
 * station-level note into a specific edit. **Per-structure attribution is v3.**
 */
export interface TerrariumStructure {
  /** Path inside the mini-document, e.g. `"world.inn"`. */
  readonly nodePath: string;
  /** The node's own id. */
  readonly id: string;
  readonly generator: string;
  /** What the document asked for, verbatim. */
  readonly provenance: {
    readonly label?: string;
    readonly params?: Readonly<Record<string, unknown>>;
    readonly tags?: readonly string[];
    /** Where it ended up, in Terrarium world columns. */
    readonly footprint?: { readonly x0: number; readonly z0: number; readonly x1: number; readonly z1: number };
    /** Walkable ground floor, in world Y; buildings only. */
    readonly floorY?: number;
    /** Cellar plane, in world Y; buildings with a basement only. */
    readonly basementFloorY?: number;
    /** Centre-line length in columns; roads and tunnels only. */
    readonly length?: number;
    /** The two node paths a tunnel joins. */
    readonly joins?: readonly [string, string];
  };
}

/** One station in the manifest — everything needed to join a note back. */
export interface TerrariumManifestStation {
  readonly index: number;
  readonly id: string;
  readonly kind: TerrariumStationKind;
  readonly grid: { readonly col: number; readonly row: number };
  readonly platform: TerrariumRect;
  readonly landing: TerrariumLanding;
  readonly structure?: TerrariumRect;
  readonly next: string;
  readonly prev: string;
  /** The commands the station's command blocks carry, by machine role. */
  readonly commands: Readonly<Record<string, string>>;
  /**
   * v3: the two travel cubes beside the landing, PREV then NEXT.
   *
   * Additive, and deliberately not a format bump — the harvester joins on `id`
   * and reads nothing here. It is in the manifest because a cube is the only
   * part of the rig whose *geometry* is a contract: a later tool that wants to
   * check "did the reviewer actually visit station 40" has the region to test
   * against, and a human debugging a dead pad has the three buried coordinates
   * without having to dig.
   */
  readonly cubes?: readonly TerrariumCube[];
  readonly provenance: TerrariumProvenance;
  /** v2, multi-stations only: the composition, and where it was transplanted. */
  readonly multi?: TerrariumMulti;
  /** v2, multi-stations only: every structure the pipeline placed. */
  readonly structures?: readonly TerrariumStructure[];
  /**
   * v2, multi-stations only: the mini-document, inline and verbatim.
   *
   * Inline rather than a path, because the join has to survive the world folder
   * being zipped, installed, walked a week later and reviewed against a
   * checkout that has moved on. The document *is* the generating configuration;
   * a reference to one would be a promise that a file still says what it said.
   */
  readonly document?: unknown;
}

/**
 * The manifest for a plan.
 *
 * Pure with respect to the plan, so a test can build it without a world; the
 * per-structure lists come from the compiled mini-stations and are simply
 * absent when the caller has none (which is the planning-only case).
 */
export function terrariumManifest(
  plan: TerrariumPlan,
  stack: PrismarineStack,
  compiled?: ReadonlyMap<string, CompiledMiniStation>,
  provenance?: Provenance,
): TerrariumManifest {
  const byId = stationIndex(plan);
  const entry = (s: TerrariumStation): TerrariumManifestStation => {
    const commands: Record<string, string> = { arrive: terrariumArrivalCommand(s) };
    const cubes = terrariumCubes(s, byId);
    for (const cube of cubes) commands[cube.direction] = cube.teleport;
    const mini = compiled?.get(s.id);
    return {
      index: s.index,
      id: s.id,
      kind: s.kind,
      grid: s.grid,
      platform: s.platform,
      landing: s.landing,
      ...(s.structure === undefined ? {} : { structure: s.structure }),
      next: s.next,
      prev: s.prev,
      commands,
      cubes,
      provenance: s.provenance,
      ...(s.multi === undefined ? {} : { multi: s.multi }),
      ...(mini === undefined
        ? {}
        : {
            structures: miniStructures(mini, s.multi as TerrariumMulti),
            document: mini.spec.document,
          }),
    };
  };
  return {
    format: TERRARIUM_MANIFEST_FORMAT,
    world: TERRARIUM_WORLD_NAME,
    minecraftVersion: stack.minecraftVersion,
    dataVersion: stack.dataVersion,
    worldSeed: TERRARIUM_WORLD_SEED.toString(),
    groundY: TERRARIUM_GROUND_Y,
    gameRules: TERRARIUM_GAME_RULES,
    stationCount: plan.stations.length,
    multiStationCount: plan.multi.length,
    spawn: entry(plan.spawn),
    stations: plan.stations.map(entry),
    ...(provenance === undefined ? {} : { provenance }),
  };
}

/**
 * Every structure one compiled mini-station placed, in a stable order.
 *
 * Buildings and plaza/props first, in the layout solver's document order, then
 * roads and tunnels — which are relations between the things above them and
 * read better after their endpoints have been named.
 */
function miniStructures(mini: CompiledMiniStation, multi: TerrariumMulti): TerrariumStructure[] {
  const { x, z } = multi.offset;
  const doc = mini.spec.document as unknown as {
    root: { id: string; children: readonly Record<string, unknown>[] };
  };
  const nodeById = new Map(doc.root.children.map((c) => [c["id"] as string, c] as const));
  const shift = (r: { x0: number; z0: number; x1: number; z1: number }) => ({
    x0: r.x0 + x,
    z0: r.z0 + z,
    x1: r.x1 + x,
    z1: r.z1 + z,
  });
  const idOf = (nodePath: string): string => nodePath.slice(nodePath.lastIndexOf(".") + 1);
  const base = (nodePath: string) => {
    const node = nodeById.get(idOf(nodePath));
    return {
      ...(node?.["label"] === undefined ? {} : { label: node["label"] as string }),
      ...(node?.["params"] === undefined
        ? {}
        : { params: node["params"] as Readonly<Record<string, unknown>> }),
      ...(node?.["tags"] === undefined ? {} : { tags: node["tags"] as readonly string[] }),
    };
  };

  const out: TerrariumStructure[] = [];
  const seen = new Set<string>();
  for (const building of mini.buildings) {
    seen.add(building.nodePath);
    out.push({
      nodePath: building.nodePath,
      id: idOf(building.nodePath),
      generator: "building.grammar@0",
      provenance: {
        ...base(building.nodePath),
        footprint: shift(building.footprint),
        floorY: building.floorY,
        ...(building.basementFloorY === undefined
          ? {}
          : { basementFloorY: building.basementFloorY }),
      },
    });
  }
  for (const prop of mini.props) {
    seen.add(prop.nodePath);
    out.push({
      nodePath: prop.nodePath,
      id: idOf(prop.nodePath),
      generator: "prop.place@0",
      provenance: { ...base(prop.nodePath), footprint: shift(prop.footprint) },
    });
  }
  // Whatever the solver placed that produced no geometry of its own — the
  // plaza primitive, most of all. It is a structure a reviewer can see and so
  // one a note can be about.
  for (const placement of mini.placements) {
    if (seen.has(placement.nodePath)) continue;
    out.push({
      nodePath: placement.nodePath,
      id: idOf(placement.nodePath),
      generator: placement.generator,
      provenance: base(placement.nodePath),
    });
  }
  for (const route of mini.routes) {
    out.push({
      nodePath: `${doc.root.id}.${route.from}->${route.to}`,
      id: `${route.from}->${route.to}`,
      generator: "road.network@0",
      provenance: { length: route.path.length },
    });
  }
  for (const tunnel of mini.tunnels) {
    out.push({
      nodePath: tunnel.id,
      id: idOf(tunnel.id),
      generator: "tunnel",
      provenance: {
        length: tunnel.path.length,
        joins: [tunnel.fromPath, tunnel.toPath] as const,
      },
    });
  }
  return out;
}

/** Every station by id, spawn included. */
export function stationIndex(plan: TerrariumPlan): Map<string, TerrariumStation> {
  const byId = new Map<string, TerrariumStation>();
  byId.set(plan.spawn.id, plan.spawn);
  for (const s of plan.stations) byId.set(s.id, s);
  return byId;
}

/**
 * Build the Terrarium and write it into `outDir/terrarium`, with its manifest
 * alongside.
 */
export async function buildTerrarium(
  outDir: string,
  provenance?: Provenance,
): Promise<TerrariumResult> {
  const stack = loadPrismarine(EMIT_MINECRAFT_VERSION);
  const plan = planTerrarium();
  const byId = stationIndex(plan);
  const cells = terrariumCells();

  // --- the multi-structure stations, compiled ------------------------------
  // Sequential rather than parallel: each compile allocates a column plan and
  // its typed-array fields, and a stable order costs nothing here while making
  // any failure's message point at one document.
  const compiled = new Map<string, CompiledMiniStation>();
  for (const station of plan.multi) {
    const spec = multiStationSpecs().find((s) => s.id === station.id) as MultiStationSpec;
    compiled.set(station.id, await compileMiniStation(spec));
  }

  // The column plan is a *substrate*, not the world: the generators sample it
  // for ground level and material, the pond digger writes into it, and only
  // the columns inside a platform are ever materialized.
  const columnPlan = devColumnPlan(
    { x0: plan.region.x0, z0: plan.region.z0, width: plan.region.width, depth: plan.region.depth },
    stack,
  );

  // --- ponds, before anything stands on them -------------------------------
  // A harbour prop only exists over water, and the placer measures itself
  // against the finished plan, so every basin is dug first. The basin is the
  // station's structure rect grown by the margin, which keeps it clear of the
  // platform edge and so of the machinery.
  // Derived from the plan's own water flags — a name literal here silently
  // beaches every water prop a later row adds (measured: the trireme, dry).
  const waterRows = new Set(PROP_EXHIBIT_PLAN.filter((r) => r.water).map((r) => r.row));
  let pondColumns = 0;
  for (const station of plan.stations) {
    if (station.kind !== "prop" || !waterRows.has(station.provenance.row)) continue;
    const r = station.structure as TerrariumRect;
    pondColumns += digPropPond(
      columnPlan,
      { x0: r.x0 - 2, z0: r.z0 - 2, x1: r.x1 + 2, z1: r.z1 + 2 },
      stack,
    );
  }

  // --- the exhibits --------------------------------------------------------
  const buildingJobs: BuildingJob[] = [];
  const propJobs: PropJob[] = [];
  for (const [i, cell] of cells.entries()) {
    const station = plan.singles[i] as TerrariumStation;
    const rect = station.structure as TerrariumRect;
    const nodePath = cell.provenance.nodePath;
    if (cell.kind === "building") {
      const e = cell.exhibit as DevExhibit;
      const seed = nodeSeed(TERRARIUM_WORLD_SEED, nodePath, e.seedSalt ?? "");
      const theme = pickTheme(seed, e.theme);
      const materials = assignMaterials(theme, 1, seed)[0] as BuildingMaterials;
      buildingJobs.push({
        nodePath,
        placement: {
          nodePath,
          id: station.id,
          translation: [rect.x0, TERRARIUM_GROUND_Y, rect.z0] as [number, number, number],
          yaw: 0,
          mirror: false,
          size: e.size,
          footprint: { x0: rect.x0, z0: rect.z0, x1: rect.x1, z1: rect.z1 },
          anchor: { x: rect.x0 + ((e.size[0] - 1) >> 1), z: rect.z0 + ((e.size[2] - 1) >> 1) },
          foundationY: TERRARIUM_GROUND_Y,
        },
        size: e.size,
        params: exhibitParams(e),
        ports: TERRARIUM_PORTS,
        seed,
        tags: [e.archetype],
        materials,
      });
    } else {
      const p = cell.prop as PropExhibit;
      const seed = nodeSeed(TERRARIUM_WORLD_SEED, nodePath, "");
      const theme = pickTheme(seed, p.theme);
      const materials = assignMaterials(theme, 1, seed)[0] as BuildingMaterials;
      propJobs.push({
        nodePath,
        prop: p.prop,
        params: { ...p.params, at: { x: rect.x0, z: rect.z0 } },
        seed,
        materials,
      });
    }
  }

  const built = buildBuildings(buildingJobs, columnPlan, stack);
  const props = buildProps({ jobs: propJobs, plan: columnPlan, stack });

  // --- the machinery -------------------------------------------------------
  const machineryBlocks: StructureBlock[] = [];
  const entities: BlockEntity[] = [];
  for (const station of [plan.spawn, ...plan.stations]) {
    const m = buildMachinery(station, terrariumCubes(station, byId), stack);
    machineryBlocks.push(...m.blocks);
    entities.push(...m.entities);
  }

  // --- the transplants -----------------------------------------------------
  // Each compiled settlement's blocks, translated into its platform. Decor
  // first and structures after, the same order the terrain emitter uses, so a
  // wall always wins over a tuft of grass that shared its column.
  const transplanted: StructureBlock[] = [];
  const transplantedBuildings: BuiltBuilding[] = [];
  const transplantedProps: PlacedProp[] = [];
  const transplantedTunnels: TunnelLandmark[] = [];
  const transplantedRoads: { path: readonly { x: number; z: number; y: number }[] }[] = [];
  for (const station of plan.multi) {
    const mini = compiled.get(station.id) as CompiledMiniStation;
    const { x: dx, z: dz } = (station.multi as TerrariumMulti).offset;
    // Clipped to the platform, and to the platform only. A block whose column
    // is not on the platform has nothing under it, and a lamp post standing in
    // the void reads as a defect in the generator rather than in the mount.
    const p = station.platform;
    const keep = (x: number, z: number): boolean => x >= p.x0 && x <= p.x1 && z >= p.z0 && z <= p.z1;
    for (const b of [...mini.artifacts.decor, ...(mini.artifacts.structures ?? [])]) {
      if (!keep(b.x + dx, b.z + dz)) continue;
      transplanted.push({ x: b.x + dx, y: b.y, z: b.z + dz, stateId: b.stateId });
    }
    for (const b of mini.buildings) transplantedBuildings.push(shiftBuilding(b, dx, dz));
    for (const p of mini.props) {
      transplantedProps.push({
        ...p,
        footprint: {
          x0: p.footprint.x0 + dx,
          z0: p.footprint.z0 + dz,
          x1: p.footprint.x1 + dx,
          z1: p.footprint.z1 + dz,
        },
      });
    }
    for (const t of mini.tunnels) {
      transplantedTunnels.push({
        id: t.id,
        from: { x: t.endpoints[0].x + dx, y: t.endpoints[0].y, z: t.endpoints[0].z + dz },
        to: { x: t.endpoints[1].x + dx, y: t.endpoints[1].y, z: t.endpoints[1].z + dz },
      });
    }
    for (const r of mini.routes) {
      transplantedRoads.push({ path: r.path.map((c) => ({ x: c.x + dx, z: c.z + dz, y: c.y })) });
    }
  }

  // --- materialize ---------------------------------------------------------
  const structureBlocks = [...built.blocks, ...props.blocks, ...transplanted, ...machineryBlocks];
  const chunks = new Map<string, EmitChunk>();
  const chunkFor = (cx: number, cz: number): EmitChunk => {
    const key = `${cx},${cz}`;
    let chunk = chunks.get(key);
    if (chunk === undefined) {
      chunk = stack.createChunk();
      // One biome for the whole world, including over a transplanted
      // settlement. Biome is grass tint and water tint and nothing a reviewer
      // is being asked about, and a chunk that straddles two platforms can
      // only have one — so it is the substrate's, everywhere, rather than a
      // seam that moves when a station is resized.
      paintChunkBiome(chunk, columnPlan.biome[0] as number);
      chunks.set(key, chunk);
    }
    return chunk;
  };

  let blockCount = 0;
  for (const station of [plan.spawn, ...plan.stations]) {
    if (station.multi === undefined) {
      blockCount += materializeColumns(chunkFor, columnPlan, station.platform);
      continue;
    }
    // A multi-station's platform is its settlement's columns, a margin ring and
    // the apron. The settlement's columns come from its own compiled plan; the
    // surround comes from the flat substrate, which agrees with the
    // mini-document's `baseHeight` by construction, so the two meet flush — and
    // that is exactly why every mini-document's *rim* is flat even when its
    // middle is not.
    const region = station.multi.region;
    const p = station.platform;
    const mini = compiled.get(station.id) as CompiledMiniStation;
    blockCount += materializeColumns(chunkFor, mini.artifacts.plan, region, station.multi.offset);
    const y = TERRARIUM_GROUND_Y;
    for (const strip of [
      { x0: p.x0, z0: p.z0, x1: p.x1, z1: region.z0 - 1, y },
      { x0: p.x0, z0: region.z1 + 1, x1: p.x1, z1: p.z1, y },
      { x0: p.x0, z0: region.z0, x1: region.x0 - 1, z1: region.z1, y },
      { x0: region.x1 + 1, z0: region.z0, x1: p.x1, z1: region.z1, y },
    ]) {
      blockCount += materializeColumns(chunkFor, columnPlan, strip);
    }
  }
  for (const block of structureBlocks) {
    if (block.y < WORLD_MIN_Y || block.y > 319) continue;
    const cx = block.x >> 4;
    const cz = block.z >> 4;
    chunkFor(cx, cz).setStateId(block.x - cx * 16, block.y, block.z - cz * 16, block.stateId);
    blockCount++;
  }
  for (const entity of entities) {
    const cx = entity.x >> 4;
    const cz = entity.z >> 4;
    chunkFor(cx, cz).setBlockEntityNbt(entity.x, entity.y, entity.z, {
      ...entity.data,
      id: { type: "string", value: entity.id },
    });
  }

  // Fences, walls and panes store their neighbours in their own state and the
  // game never recomputes it, so the connection pass runs over the finished
  // world exactly as it does for a compiled one.
  const connections = applyConnectionStates(chunks, structureBlocks, stack);

  const worldDir = path.join(path.resolve(outDir), TERRARIUM_WORLD_NAME);
  const written = await writeWorldFiles({
    chunks,
    worldDir,
    levelName: TERRARIUM_WORLD_NAME,
    spawn: { x: plan.spawn.landing.x, y: plan.spawn.landing.y, z: plan.spawn.landing.z },
    stack,
    gameRules: TERRARIUM_GAME_RULES,
    gameType: TERRARIUM_GAME_TYPE,
  });

  const manifest = terrariumManifest(plan, stack, compiled, provenance);
  const manifestPath = path.join(path.resolve(outDir), TERRARIUM_MANIFEST_NAME);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  return {
    plan,
    manifest,
    worldDir: written.worldDir,
    manifestPath,
    levelDatPath: written.levelDatPath,
    regionFiles: written.regionFiles,
    chunkCount: written.chunkCount,
    blockCount,
    pondColumns,
    blockEntityCount: entities.length,
    stationCount: plan.stations.length,
    multiStationCount: plan.multi.length,
    buildings: [...built.built, ...transplantedBuildings],
    placedProps: [...props.placed, ...transplantedProps],
    tunnels: transplantedTunnels,
    roads: transplantedRoads,
    structureBlocks,
    entities,
    connections,
    minecraftVersion: stack.minecraftVersion,
    dataVersion: stack.dataVersion,
    compiled,
  };
}

/**
 * Write one rectangle of a plan's columns into the world.
 *
 * A bounded, floored version of the terrain emitter's column fill: soil and
 * surface exactly as the plan holds them (so a dug basin arrives as sand and
 * water rather than as a hole in the grass), stone from there down to
 * {@link TERRARIUM_PLATFORM_FLOOR}, and nothing at all outside the rectangle. No
 * bedrock: the underside of a platform is meant to be *seen*, and a course of
 * bedrock under every station would read as a floor the world once had.
 *
 * `rect` is in **world** columns and `offset` is what was added to the plan's
 * own coordinates to get there — zero for the substrate, and the platform's
 * displacement for a transplanted settlement. Cave spans are punched last, as
 * `cave_air`, exactly as the emitter does it: a transplanted pair of cellars is
 * joined by a bored gallery, and a fill that ignored the bore would seal it.
 */
function materializeColumns(
  chunkFor: (cx: number, cz: number) => EmitChunk,
  plan: ColumnPlan,
  rect: TerrariumRect,
  offset: { readonly x: number; readonly z: number } = { x: 0, z: 0 },
): number {
  const { region } = plan;
  const stone = plan.states.stone;
  let count = 0;
  for (let z = rect.z0; z <= rect.z1; z++) {
    const j = z - offset.z - region.z0;
    if (j < 0 || j >= region.depth) continue;
    for (let x = rect.x0; x <= rect.x1; x++) {
      const i = x - offset.x - region.x0;
      if (i < 0 || i >= region.width) continue;
      const idx = j * region.width + i;
      const chunk = chunkFor(x >> 4, z >> 4);
      const lx = x - (x >> 4) * 16;
      const lz = z - (z >> 4) * 16;

      const top = plan.ground[idx] as number;
      const soilDepth = plan.soil[idx] as number;
      const soilBase = top - soilDepth;
      if (soilBase - 1 >= TERRARIUM_PLATFORM_FLOOR) {
        chunk.fillColumn(lx, lz, TERRARIUM_PLATFORM_FLOOR, soilBase - 1, stone);
        count += soilBase - TERRARIUM_PLATFORM_FLOOR;
      }
      if (soilDepth > 0 && top - 1 >= soilBase) {
        chunk.fillColumn(lx, lz, soilBase, top - 1, plan.subsurface[idx] as number);
        count += top - soilBase;
      }
      chunk.setStateId(lx, top, lz, plan.surface[idx] as number);
      count += 1;

      const kind = plan.fluidKind[idx];
      if (kind !== FluidKind.NONE) {
        const fluidState = kind === FluidKind.LAVA ? plan.states.lava : plan.states.water;
        const surfaceY = plan.fluidTop[idx] as number;
        if (surfaceY > top) {
          chunk.fillColumn(lx, lz, top + 1, surfaceY, fluidState);
          count += surfaceY - top;
        }
      } else if (plan.snow[idx] === 1 && top + 1 <= 319) {
        chunk.setStateId(lx, top + 1, lz, plan.states.snowLayer);
        count += 1;
      }

      const caves = plan.caves;
      if (caves === undefined) continue;
      const end = caves.spans.offsets[idx + 1] as number;
      for (let k = caves.spans.offsets[idx] as number; k < end; k++) {
        const lo = Math.max(caves.spans.lo[k] as number, TERRARIUM_PLATFORM_FLOOR);
        const hi = caves.spans.hi[k] as number;
        if (hi < lo) continue;
        chunk.fillColumn(lx, lz, lo, hi, plan.states.caveAir);
        count -= hi - lo + 1;
      }
    }
  }
  return count;
}

/** Paint a whole chunk one biome, at the 4×4×4 resolution the format wants. */
function paintChunkBiome(chunk: EmitChunk, biomeId: number): void {
  for (let cellZ = 0; cellZ < 4; cellZ++) {
    for (let cellX = 0; cellX < 4; cellX++) {
      for (let y = WORLD_MIN_Y; y < WORLD_MIN_Y + 384; y += 4) {
        chunk.setBiomeAt(cellX * 4, y, cellZ * 4, biomeId);
      }
    }
  }
}
