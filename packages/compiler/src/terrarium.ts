/**
 * What a station is exhibiting.
 *
 * `"multi"` is v2's addition: a station whose content is a whole compiled
 * mini-settlement rather than one generator's output.
 */
export type TerrariumStationKind = "building" | "prop" | "spawn" | "multi";

/** Where a station's exhibit came from — enough to regenerate it exactly. */
export interface TerrariumProvenance {
  readonly kind: TerrariumStationKind;
  /** The registry row this cell belongs to, e.g. `"cottage"`, `"harbour"`. */
  readonly row: string;
  /** Position within the row, west to east. */
  readonly column: number;
  /** The generator family: an archetype name, or a prop name. */
  readonly family: string;
  /** The node path the seed is derived from — the same one the dev world uses. */
  readonly nodePath: string;
  readonly theme?: string;
  readonly roof?: string;
  readonly floors?: number;
  /** Unrotated extents, as the row laid the cell out. */
  readonly size: readonly [number, number, number];
  /** The cell's `seedSalt`, when its row rerolls rather than varies. */
  readonly seedSalt?: string;
  /** Extra generator params the cell carries. */
  readonly params?: Readonly<Record<string, unknown>>;
}

/** An inclusive rectangle of world columns, with the Y its top sits at. */
export interface TerrariumRect {
  readonly x0: number;
  readonly z0: number;
  readonly x1: number;
  readonly z1: number;
  readonly y: number;
}

/** Where a teleport lands, and the command string that gets there. */
export interface TerrariumLanding {
  readonly x: number;
  readonly y: number;
  readonly z: number;
  /** The `tp` argument triple — block centres, so the player lands on the plate. */
  readonly tp: string;
}

/** One station, planned. */
export interface TerrariumStation {
  /** Index in walk order; the spawn station is not in this sequence. */
  readonly index: number;
  readonly id: string;
  readonly kind: TerrariumStationKind;
  readonly grid: { readonly col: number; readonly row: number };
  readonly platform: TerrariumRect;
  readonly landing: TerrariumLanding;
  /** Where the exhibit itself stands; absent on the spawn station. */
  readonly structure?: TerrariumRect;
  /** Station ids the NEXT and PREV buttons go to. */
  readonly next: string;
  readonly prev: string;
  readonly provenance: TerrariumProvenance;
  /** The mini-settlement this station exhibits; present only on a `multi` one. */
  readonly multi?: TerrariumMulti;
}

/** A multi-structure station's mini-settlement, as the plan knows it. */
export interface TerrariumMulti {
  readonly kind: MultiStationKind;
  readonly title: string;
  readonly question: string;
  /** The mini-document's own name, and the seed it was compiled under. */
  readonly document: string;
  readonly worldSeed: number;
  /**
   * The columns the transplanted settlement occupies, in Terrarium world space.
   *
   * Equal to the compiled region translated by
   * {@link TerrariumMulti.offset}; the apron the machinery stands on is south
   * of it and belongs to the platform, not to the settlement.
   */
  readonly region: TerrariumRect;
  /** What was added to every compiled coordinate to get here. */
  readonly offset: { readonly x: number; readonly z: number };
}

/** The whole Terrarium, before anything is built. */
export interface TerrariumPlan {
  readonly spawn: TerrariumStation;
  readonly stations: readonly TerrariumStation[];
  /** Just the single-structure stations, in walk order. */
  readonly singles: readonly TerrariumStation[];
  /** Just the multi-structure stations, in walk order — the v2 band. */
  readonly multi: readonly TerrariumStation[];
  /** Columns spanned by every platform, for the column plan's region. */
  readonly region: { readonly x0: number; readonly z0: number; readonly width: number; readonly depth: number };
  readonly columns: number;
}

/** One exhibit as the rig sees it, before it is given a platform. */
interface TerrariumCell {
  readonly id: string;
  readonly kind: "building" | "prop";
  /** Extents on the ground the platform has to fit, already rotated. */
  readonly footprint: readonly [number, number];
  readonly provenance: TerrariumProvenance;
  /** The dev-world cell this came from, for the builder. */
  readonly exhibit?: DevExhibit;
  readonly prop?: PropExhibit;
}

/** Rotated ground extents of a prop cell. */
function propExtents(cell: PropExhibit): [number, number] {
  const yaw = (cell.params["yaw"] ?? 0) as StructureYaw;
  const [w, , d] = cell.size;
  return yaw === 90 || yaw === 270 ? [d, w] : [w, d];
}

/**
 * Every exhibit in the registry, in station order.
 *
 * Read from the dev world's own planner rather than from the row files
 * directly, so a row added to the dev world shows up here without this file
 * being touched — the same argument that made `EXTRA_EXHIBIT_ROWS` a seam.
 * The context strips are excluded: a context cell is a building *and its
 * ground*, and putting one on a flat platform would exhibit neither.
 */
export function terrariumCells(): readonly TerrariumCell[] {
  const cells: TerrariumCell[] = [];
  for (const e of planDevGrid().exhibits) {
    cells.push({
      id: `${e.row}__${e.id}`,
      kind: "building",
      footprint: [e.size[0], e.size[2]],
      exhibit: e,
      provenance: {
        kind: "building",
        row: e.row,
        column: e.column,
        family: e.archetype,
        nodePath: `rig.${e.row}.${e.id}`,
        theme: e.theme,
        roof: e.roof,
        floors: e.floors,
        size: e.size,
        ...(e.seedSalt === undefined ? {} : { seedSalt: e.seedSalt }),
        ...(e.params === undefined ? {} : { params: e.params }),
      },
    });
  }
  for (const p of planPropExhibits().exhibits) {
    cells.push({
      id: `prop_${p.row}__${p.id}`,
      kind: "prop",
      footprint: propExtents(p),
      prop: p,
      provenance: {
        kind: "prop",
        row: p.row,
        column: p.column,
        family: p.prop,
        nodePath: `rig.props.${p.row}.${p.id}`,
        theme: p.theme,
        size: p.size,
        params: p.params,
      },
    });
  }
  return cells;
}

/** Platform extents for a cell's ground footprint. */
function platformSize(footprint: readonly [number, number]): [number, number] {
  const width = Math.max(footprint[0] + TERRARIUM_MARGIN * 2, TERRARIUM_MIN_WIDTH);
  const depth = footprint[1] + TERRARIUM_MARGIN * 2 + TERRARIUM_APRON;
  return [width, depth];
}

/** Block-centre coordinates for a `tp` argument triple. */
function tpTriple(x: number, y: number, z: number): string {
  return `${x + 0.5} ${y} ${z + 0.5}`;
}

/**
 * Lay every station out.
 *
 * A square-ish grid on a uniform pitch, in registry order, reading west to
 * east and then south — so "station 40" is somewhere you can find by walking,
 * and NEXT follows the same order the manifest does. Platforms are sized per
 * station and left-aligned in their cell, because a uniform platform big
 * enough for the widest exhibit would put a cottage in the middle of an acre.
 *
 * The multi-structure stations get a **band of their own**, south of the grid
 * and laid west to east on a per-station pitch. Two reasons, both practical:
 * their platforms are three to eight times the width of a cottage's, so folding
 * them into the uniform grid pitch would spread a hundred and fifty single
 * stations over eight times the ground for no gain; and keeping the grid's
 * geometry untouched means a v1 station is at the same coordinates it was, so a
 * screenshot from an earlier session still lines up with the world.
 *
 * Node paths keep their `rig.` prefix deliberately. They are seed material —
 * `nodeSeed(worldSeed, nodePath)` is what picks an exhibit's theme and
 * materials — so renaming them would silently reroll every single-structure
 * station's appearance, which is exactly the kind of unexplained diff the
 * Terrarium exists to make impossible.
 */
export function planTerrarium(): TerrariumPlan {
  const cells = terrariumCells();
  const sizes = cells.map((c) => platformSize(c.footprint));
  const spawnSize: [number, number] = [TERRARIUM_MIN_WIDTH, TERRARIUM_MIN_WIDTH + TERRARIUM_APRON];

  const pitchX = Math.max(spawnSize[0], ...sizes.map((s) => s[0])) + TERRARIUM_GAP;
  const pitchZ = Math.max(spawnSize[1], ...sizes.map((s) => s[1])) + TERRARIUM_GAP;
  // The spawn platform takes the first grid cell, so the walk starts where the
  // player does and the numbering of the stations still starts at one.
  const cols = Math.ceil(Math.sqrt(cells.length + 1));

  const place = (slot: number, size: readonly [number, number]) => {
    const col = slot % cols;
    const row = Math.floor(slot / cols);
    const x0 = col * pitchX;
    const z0 = row * pitchZ;
    const platform: TerrariumRect = {
      x0,
      z0,
      x1: x0 + size[0] - 1,
      z1: z0 + size[1] - 1,
      y: TERRARIUM_GROUND_Y,
    };
    const cx = x0 + (size[0] >> 1);
    const cz = z0 + size[1] - 5;
    const landing: TerrariumLanding = {
      x: cx,
      y: TERRARIUM_GROUND_Y + 1,
      z: cz,
      tp: tpTriple(cx, TERRARIUM_GROUND_Y + 1, cz),
    };
    return { col, row, platform, landing };
  };

  const spawnPlaced = place(0, spawnSize);
  const specs = multiStationSpecs();
  // Walk order, and so the ids NEXT and PREV chase: the grid first, the band
  // after it. Computed before the stations themselves, because a station has to
  // name its neighbours and the last single's neighbour is the first multi.
  const order = [...cells.map((c) => c.id), ...specs.map((s) => s.id)];
  const neighbour = (i: number, step: number): string =>
    order[(i + step + order.length) % order.length] as string;

  const singles: TerrariumStation[] = cells.map((cell, i) => {
    const size = sizes[i] as [number, number];
    const p = place(i + 1, size);
    const sw = cell.footprint[0];
    const sd = cell.footprint[1];
    const sx = p.platform.x0 + ((size[0] - sw) >> 1);
    const sz = p.platform.z0 + TERRARIUM_MARGIN;
    return {
      index: i,
      id: cell.id,
      kind: cell.kind,
      grid: { col: p.col, row: p.row },
      platform: p.platform,
      landing: p.landing,
      structure: { x0: sx, z0: sz, x1: sx + sw - 1, z1: sz + sd - 1, y: TERRARIUM_GROUND_Y },
      // Wrapping, at both ends: a reviewer who overshoots the last station
      // should arrive at the first, not walk off the end of the world.
      next: neighbour(i, 1),
      prev: neighbour(i, -1),
      provenance: cell.provenance,
    };
  });

  // --- the multi band ------------------------------------------------------
  // One row, south of the grid. A platform is its settlement's region, a margin
  // ring, and the apron the machinery stands on. The ring is not decoration:
  // the layout solver will happily put a building hard against the region's
  // edge, and a gable overhang or a porch lamp then lands a block or two
  // outside it. Without ground under those columns they would be blocks in the
  // void — which is a lint failure, and worse, looks like a broken generator.
  const gridRows = Math.ceil((cells.length + 1) / cols);
  const bandZ0 = gridRows * pitchZ + TERRARIUM_BAND_GAP;
  let bandX = 0;
  const multi: TerrariumStation[] = specs.map((spec, k) => {
    const i = cells.length + k;
    const [w, d] = spec.size;
    const x0 = bandX + TERRARIUM_MARGIN;
    const z0 = bandZ0 + TERRARIUM_MARGIN;
    const platform: TerrariumRect = {
      x0: bandX,
      z0: bandZ0,
      x1: x0 + w - 1 + TERRARIUM_MARGIN,
      z1: z0 + d - 1 + TERRARIUM_MARGIN + TERRARIUM_APRON,
      y: TERRARIUM_GROUND_Y,
    };
    bandX = platform.x1 + 1 + TERRARIUM_GAP;
    const cx = platform.x0 + ((platform.x1 - platform.x0 + 1) >> 1);
    const cz = platform.z1 - 4;
    const region: TerrariumRect = { x0, z0, x1: x0 + w - 1, z1: z0 + d - 1, y: TERRARIUM_GROUND_Y };
    return {
      index: i,
      id: spec.id,
      kind: "multi" as const,
      grid: { col: k, row: gridRows },
      platform,
      landing: {
        x: cx,
        y: TERRARIUM_GROUND_Y + 1,
        z: cz,
        tp: tpTriple(cx, TERRARIUM_GROUND_Y + 1, cz),
      },
      structure: region,
      next: neighbour(i, 1),
      prev: neighbour(i, -1),
      provenance: multiProvenance(spec, k),
      multi: {
        kind: spec.kind,
        title: spec.title,
        question: spec.question,
        document: spec.document.meta.name,
        worldSeed: spec.document.meta.worldSeed as number,
        region,
        // `centeredRegion` puts a compiled document's region at
        // `(-floor(w/2), -floor(d/2))`, so this is the region's north-west
        // corner in world space minus the same corner in document space.
        offset: { x: x0 + (w >> 1), z: z0 + (d >> 1) },
      },
    };
  });

  const stations = [...singles, ...multi];

  const spawn: TerrariumStation = {
    index: -1,
    id: TERRARIUM_SPAWN_ID,
    kind: "spawn",
    grid: { col: spawnPlaced.col, row: spawnPlaced.row },
    platform: spawnPlaced.platform,
    landing: spawnPlaced.landing,
    next: (stations[0] as TerrariumStation).id,
    prev: (stations[stations.length - 1] as TerrariumStation).id,
    provenance: {
      kind: "spawn",
      row: "_start",
      column: 0,
      family: "instructions",
      nodePath: "rig._start",
      size: [spawnSize[0], 1, spawnSize[1]],
    },
  };

  const all = [spawn, ...stations];
  const x0 = Math.min(...all.map((s) => s.platform.x0)) - 2;
  const z0 = Math.min(...all.map((s) => s.platform.z0)) - 2;
  const x1 = Math.max(...all.map((s) => s.platform.x1)) + 2;
  const z1 = Math.max(...all.map((s) => s.platform.z1)) + 2;
  const columns = all.reduce(
    (sum, s) => sum + (s.platform.x1 - s.platform.x0 + 1) * (s.platform.z1 - s.platform.z0 + 1),
    0,
  );

  return {
    spawn,
    stations,
    singles,
    multi,
    region: { x0, z0, width: x1 - x0 + 1, depth: z1 - z0 + 1 },
    columns,
  };
}

/**
 * A multi-station's provenance.
 *
 * The single-structure fields are filled in with what a *document* has instead
 * of what a cell has — the row is the composition's kind, the family is the
 * mini-document's name, and `params` carries the question the station is
 * asking. The per-structure detail lives in the manifest's `structures[]`,
 * which is where it can be listed rather than squeezed into one record.
 */
function multiProvenance(spec: MultiStationSpec, column: number): TerrariumProvenance {
  return {
    kind: "multi",
    row: spec.kind,
    column,
    family: spec.document.meta.name,
    // Not a seed path: a multi-station's content is seeded by its own
    // document's `worldSeed`, and this names the station rather than a
    // generator. It is here because every station has one.
    nodePath: `terrarium.multi.${spec.kind}`,
    size: [spec.size[0], 1, spec.size[1]],
    params: { question: spec.question, worldSeed: spec.document.meta.worldSeed },
  };
}

