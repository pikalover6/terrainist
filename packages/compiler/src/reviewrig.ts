/** One button on the machinery wall. */
export interface RigButton {
  /** Slot index into {@link RIG_BUTTON_SLOTS}. */
  readonly slot: number;
  readonly label: string;
  /** Second sign line — what the button does, in three words. */
  readonly hint: string;
  readonly command: string;
}

/** The machinery a station carries, as blocks and compounds. */
interface Machinery {
  readonly blocks: readonly StructureBlock[];
  readonly entities: readonly BlockEntity[];
}

/**
 * The four commands a station's buttons run.
 *
 * Exported because the manifest↔world test asserts on exactly these strings:
 * the property that matters is that the command block on the platform runs the
 * command the manifest says it does, and a test that rebuilt the string from
 * its own template would only be checking itself.
 */
export function rigButtons(station: RigStation, byId: ReadonlyMap<string, RigStation>): RigButton[] {
  const landingOf = (id: string): string =>
    (byId.get(id) as RigStation).landing.tp;
  const buttons: RigButton[] = [
    { slot: 0, label: "NEXT", hint: "go forward", command: `tp @p ${landingOf(station.next)}` },
  ];
  if (station.kind === "spawn") return buttons;
  buttons.push(
    { slot: 1, label: "PREV", hint: "go back", command: `tp @p ${landingOf(station.prev)}` },
    { slot: 2, label: "PASS", hint: "looks right", command: `say VERDICT ${station.id} pass` },
    { slot: 3, label: "FAIL", hint: "looks wrong", command: `say VERDICT ${station.id} fail` },
  );
  return buttons;
}

/** The command the arrival plate's command block runs. */
export function rigArrivalCommand(station: RigStation): string {
  return `say >> STATION ${station.id}`;
}

/**
 * The two label signs a station carries, as their four lines each.
 *
 * One says what the station *is* — its id and its place in the registry — and
 * one says what the generator was *told*, which is the pair a reviewer needs
 * to turn "this roof is wrong" into a reproducible complaint.
 */
export function rigSignLines(station: RigStation): [string[], string[]] {
  const p = station.provenance;
  if (station.kind === "spawn") {
    return [
      ["REVIEW RIG", "", "step on the plate", "press NEXT"],
      ["PASS / FAIL", "record a verdict", "type in chat to", "leave a comment"],
    ];
  }
  const size = `${p.size[0]}x${p.size[1]}x${p.size[2]}`;
  const extras = Object.keys(p.params ?? {}).join(" ");
  return [
    [`#${station.index + 1} ${p.row}`, truncate(station.id, 15), p.family, `col ${p.column}`],
    [
      `size ${size}`,
      p.roof === undefined ? `theme ${p.theme ?? "-"}` : `roof ${p.roof} f${p.floors ?? 1}`,
      p.roof === undefined ? extras : `theme ${p.theme ?? "-"}`,
      p.seedSalt === undefined ? extras : `salt ${p.seedSalt}`,
    ],
  ];
}

/** The four instruction signs on the spawn platform. */
const RIG_INSTRUCTIONS: readonly (readonly string[])[] = Object.freeze([
  ["HOW THIS WORKS", "1. press NEXT", "2. look at the", "   one building"],
  ["3. PASS or FAIL", "4. say anything", "   in chat: it", "   is recorded"],
  ["the plate you", "land on marks", "which station", "your notes join"],
  ["NEXT wraps at", "the last one.", "nothing here", "is destructive."],
]);

function truncate(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max - 1)}~`;
}

/**
 * Build one station's machinery.
 *
 * The geometry is fixed relative to the platform's south edge, which is what
 * makes the rig navigable: the plate is always four blocks north of the wall,
 * the wall always carries the buttons in the same order, and a reviewer who
 * has done one station has done all of them.
 */
function buildMachinery(
  station: RigStation,
  buttons: readonly RigButton[],
  stack: PrismarineStack,
): Machinery {
  const blocks: StructureBlock[] = [];
  const entities: BlockEntity[] = [];
  const y = RIG_GROUND_Y;
  const state = (name: string, props?: Record<string, string>): number =>
    (props === undefined ? stack.blockByName(name)?.stateId : stack.blockStateOf(name, props)) ?? 0;

  const cx = station.landing.x;
  const zWall = station.platform.z1 - 1;
  const zButtons = zWall - 1;
  const zLand = station.landing.z;

  // --- the arrival plate, on its command block ------------------------------
  // The plate strongly powers the block beneath it, so an impulse command
  // block directly under the landing spot fires once per arrival — which is
  // exactly the granularity the log harvester wants.
  blocks.push({ x: cx, y, z: zLand, stateId: state("command_block", { conditional: "false", facing: "up" }) });
  blocks.push({
    x: cx,
    y: y + 1,
    z: zLand,
    stateId: state("stone_pressure_plate", { powered: "false" }),
  });
  entities.push(
    commandBlockEntity(cx, y, zLand, rigArrivalCommand(station), {
      auto: false,
      trackOutput: false,
      customName: "@",
    }),
  );

  // --- the label signs -----------------------------------------------------
  // Standing signs on the platform, one either side of the plate, facing south
  // so they read from the spot the player lands on.
  const [lineA, lineB] = rigSignLines(station);
  const signState = state("oak_sign", { rotation: "0", waterlogged: "false" });
  for (const [dx, lines] of [
    [-2, lineA],
    [2, lineB],
  ] as const) {
    blocks.push({ x: cx + dx, y: y + 1, z: zLand - 1, stateId: signState });
    entities.push(signEntity(cx + dx, y + 1, zLand - 1, { front: lines, waxed: true }));
  }

  // --- the spawn platform's instructions -----------------------------------
  if (station.kind === "spawn") {
    for (const [i, lines] of RIG_INSTRUCTIONS.entries()) {
      const x = cx - 3 + i * 2;
      blocks.push({ x, y: y + 1, z: zLand - 3, stateId: signState });
      entities.push(signEntity(x, y + 1, zLand - 3, { front: lines, waxed: true }));
    }
  }

  // --- the machinery wall --------------------------------------------------
  // Two courses of brick from `cx - 4` to `cx + 4`, with a command block
  // standing in the lower course behind each button. The button is on the
  // wall's north face, so it is pressed from the platform, and its label sign
  // is on the same face one block up.
  const bricks = state("stone_bricks");
  const slotOf = new Map(buttons.map((b) => [RIG_BUTTON_SLOTS[b.slot] as number, b]));
  for (let dx = -4; dx <= 4; dx++) {
    const x = cx + dx;
    const button = slotOf.get(dx);
    blocks.push({
      x,
      y: y + 1,
      z: zWall,
      stateId:
        button === undefined
          ? bricks
          : state("command_block", { conditional: "false", facing: "up" }),
    });
    blocks.push({ x, y: y + 2, z: zWall, stateId: bricks });
    if (button === undefined) continue;
    entities.push(
      commandBlockEntity(x, y + 1, zWall, button.command, {
        auto: false,
        trackOutput: false,
        customName: button.label,
      }),
    );
    blocks.push({
      x,
      y: y + 1,
      z: zButtons,
      stateId: state("stone_button", { face: "wall", facing: "north", powered: "false" }),
    });
    blocks.push({
      x,
      y: y + 2,
      z: zButtons,
      stateId: state("oak_wall_sign", { facing: "north", waterlogged: "false" }),
    });
    entities.push(
      signEntity(x, y + 2, zButtons, {
        front: [button.label, button.hint, "", ""],
        waxed: true,
      }),
    );
  }

  return { blocks, entities };
}

