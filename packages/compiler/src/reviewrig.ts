export const RIG_APRON = 7;

/** Void between two platforms, in blocks — generous, so no two stations share a frame. */
export const RIG_GAP = 24;

/** Narrowest a platform may be: the machinery bank needs eleven columns. */
export const RIG_MIN_WIDTH = 11 + RIG_MARGIN * 2;

