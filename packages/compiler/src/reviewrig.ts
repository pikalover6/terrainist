/** What a station is exhibiting. */
export type RigStationKind = "building" | "prop" | "spawn";

/** Where a station's exhibit came from — enough to regenerate it exactly. */
export interface RigProvenance {
  readonly kind: RigStationKind;
  /** The registry row this cell belongs to, e.g. `"cottage"`, `"harbour"`. */
  readonly row: string;
  /** Position within the row, west to east. */
  readonly column: number;
  /** The generator family: an archetype name, or a prop name. */
  readonly family: string;
  /** The node path the seed is derived from — the same one the dev world uses. */
  readonly nodePath: string;
  readonly theme?: string;
  readonly roof?: string;
  readonly floors?: number;
  /** Unrotated extents, as the row laid the cell out. */
  readonly size: readonly [number, number, number];
  /** The cell's `seedSalt`, when its row rerolls rather than varies. */
  readonly seedSalt?: string;
  /** Extra generator params the cell carries. */
  readonly params?: Readonly<Record<string, unknown>>;
}

/** An inclusive rectangle of world columns, with the Y its top sits at. */
export interface RigRect {
  readonly x0: number;
  readonly z0: number;
  readonly x1: number;
  readonly z1: number;
  readonly y: number;
}

/** Where a teleport lands, and the command string that gets there. */
export interface RigLanding {
  readonly x: number;
  readonly y: number;
  readonly z: number;
  /** The `tp` argument triple — block centres, so the player lands on the plate. */
  readonly tp: string;
}

/** One station, planned. */
export interface RigStation {
  /** Index in walk order; the spawn station is not in this sequence. */
  readonly index: number;
  readonly id: string;
  readonly kind: RigStationKind;
  readonly grid: { readonly col: number; readonly row: number };
  readonly platform: RigRect;
  readonly landing: RigLanding;
  /** Where the exhibit itself stands; absent on the spawn station. */
  readonly structure?: RigRect;
  /** Station ids the NEXT and PREV buttons go to. */
  readonly next: string;
  readonly prev: string;
  readonly provenance: RigProvenance;
}

/** The whole rig, before anything is built. */
export interface RigPlan {
  readonly spawn: RigStation;
  readonly stations: readonly RigStation[];
  /** Columns spanned by every platform, for the column plan's region. */
  readonly region: { readonly x0: number; readonly z0: number; readonly width: number; readonly depth: number };
  readonly columns: number;
}

/** One exhibit as the rig sees it, before it is given a platform. */
interface RigCell {
  readonly id: string;
  readonly kind: "building" | "prop";
  /** Extents on the ground the platform has to fit, already rotated. */
  readonly footprint: readonly [number, number];
  readonly provenance: RigProvenance;
  /** The dev-world cell this came from, for the builder. */
  readonly exhibit?: DevExhibit;
  readonly prop?: PropExhibit;
}

/** Rotated ground extents of a prop cell. */
function propExtents(cell: PropExhibit): [number, number] {
  const yaw = (cell.params["yaw"] ?? 0) as StructureYaw;
  const [w, , d] = cell.size;
  return yaw === 90 || yaw === 270 ? [d, w] : [w, d];
}

/**
 * Every exhibit in the registry, in station order.
 *
 * Read from the dev world's own planner rather than from the row files
 * directly, so a row added to the dev world shows up here without this file
 * being touched — the same argument that made `EXTRA_EXHIBIT_ROWS` a seam.
 * The context strips are excluded: a context cell is a building *and its
 * ground*, and putting one on a flat platform would exhibit neither.
 */
export function rigCells(): readonly RigCell[] {
  const cells: RigCell[] = [];
  for (const e of planDevGrid().exhibits) {
    cells.push({
      id: `${e.row}__${e.id}`,
      kind: "building",
      footprint: [e.size[0], e.size[2]],
      exhibit: e,
      provenance: {
        kind: "building",
        row: e.row,
        column: e.column,
        family: e.archetype,
        nodePath: `rig.${e.row}.${e.id}`,
        theme: e.theme,
        roof: e.roof,
        floors: e.floors,
        size: e.size,
        ...(e.seedSalt === undefined ? {} : { seedSalt: e.seedSalt }),
        ...(e.params === undefined ? {} : { params: e.params }),
      },
    });
  }
  for (const p of planPropExhibits().exhibits) {
    cells.push({
      id: `prop_${p.row}__${p.id}`,
      kind: "prop",
      footprint: propExtents(p),
      prop: p,
      provenance: {
        kind: "prop",
        row: p.row,
        column: p.column,
        family: p.prop,
        nodePath: `rig.props.${p.row}.${p.id}`,
        theme: p.theme,
        size: p.size,
        params: p.params,
      },
    });
  }
  return cells;
}

/** Platform extents for a cell's ground footprint. */
function platformSize(footprint: readonly [number, number]): [number, number] {
  const width = Math.max(footprint[0] + RIG_MARGIN * 2, RIG_MIN_WIDTH);
  const depth = footprint[1] + RIG_MARGIN * 2 + RIG_APRON;
  return [width, depth];
}

/** Block-centre coordinates for a `tp` argument triple. */
function tpTriple(x: number, y: number, z: number): string {
  return `${x + 0.5} ${y} ${z + 0.5}`;
}

/**
 * Lay every station out.
 *
 * A square-ish grid on a uniform pitch, in registry order, reading west to
 * east and then south — so "station 40" is somewhere you can find by walking,
 * and NEXT follows the same order the manifest does. Platforms are sized per
 * station and left-aligned in their cell, because a uniform platform big
 * enough for the widest exhibit would put a cottage in the middle of an acre.
 */
export function planReviewRig(): RigPlan {
  const cells = rigCells();
  const sizes = cells.map((c) => platformSize(c.footprint));
  const spawnSize: [number, number] = [RIG_MIN_WIDTH, RIG_MIN_WIDTH + RIG_APRON];

  const pitchX = Math.max(spawnSize[0], ...sizes.map((s) => s[0])) + RIG_GAP;
  const pitchZ = Math.max(spawnSize[1], ...sizes.map((s) => s[1])) + RIG_GAP;
  // The spawn platform takes the first grid cell, so the walk starts where the
  // player does and the numbering of the stations still starts at one.
  const cols = Math.ceil(Math.sqrt(cells.length + 1));

  const place = (slot: number, size: readonly [number, number]) => {
    const col = slot % cols;
    const row = Math.floor(slot / cols);
    const x0 = col * pitchX;
    const z0 = row * pitchZ;
    const platform: RigRect = {
      x0,
      z0,
      x1: x0 + size[0] - 1,
      z1: z0 + size[1] - 1,
      y: RIG_GROUND_Y,
    };
    const cx = x0 + (size[0] >> 1);
    const cz = z0 + size[1] - 5;
    const landing: RigLanding = {
      x: cx,
      y: RIG_GROUND_Y + 1,
      z: cz,
      tp: tpTriple(cx, RIG_GROUND_Y + 1, cz),
    };
    return { col, row, platform, landing };
  };

  const spawnPlaced = place(0, spawnSize);
  const stations: RigStation[] = cells.map((cell, i) => {
    const size = sizes[i] as [number, number];
    const p = place(i + 1, size);
    const sw = cell.footprint[0];
    const sd = cell.footprint[1];
    const sx = p.platform.x0 + ((size[0] - sw) >> 1);
    const sz = p.platform.z0 + RIG_MARGIN;
    return {
      index: i,
      id: cell.id,
      kind: cell.kind,
      grid: { col: p.col, row: p.row },
      platform: p.platform,
      landing: p.landing,
      structure: { x0: sx, z0: sz, x1: sx + sw - 1, z1: sz + sd - 1, y: RIG_GROUND_Y },
      // Wrapping, at both ends: a reviewer who overshoots the last station
      // should arrive at the first, not walk off the end of the world.
      next: (cells[(i + 1) % cells.length] as RigCell).id,
      prev: (cells[(i - 1 + cells.length) % cells.length] as RigCell).id,
      provenance: cell.provenance,
    };
  });

  const spawn: RigStation = {
    index: -1,
    id: RIG_SPAWN_ID,
    kind: "spawn",
    grid: { col: spawnPlaced.col, row: spawnPlaced.row },
    platform: spawnPlaced.platform,
    landing: spawnPlaced.landing,
    next: (stations[0] as RigStation).id,
    prev: (stations[stations.length - 1] as RigStation).id,
    provenance: {
      kind: "spawn",
      row: "_start",
      column: 0,
      family: "instructions",
      nodePath: "rig._start",
      size: [spawnSize[0], 1, spawnSize[1]],
    },
  };

  const all = [spawn, ...stations];
  const x0 = Math.min(...all.map((s) => s.platform.x0)) - 2;
  const z0 = Math.min(...all.map((s) => s.platform.z0)) - 2;
  const x1 = Math.max(...all.map((s) => s.platform.x1)) + 2;
  const z1 = Math.max(...all.map((s) => s.platform.z1)) + 2;
  const columns = all.reduce(
    (sum, s) => sum + (s.platform.x1 - s.platform.x0 + 1) * (s.platform.z1 - s.platform.z0 + 1),
    0,
  );

  return {
    spawn,
    stations,
    region: { x0, z0, width: x1 - x0 + 1, depth: z1 - z0 + 1 },
    columns,
  };
}

