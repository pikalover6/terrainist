/**
 * The human-review rig — one exhibit, one platform, one verdict.
 *
 * The dev world is a *contact sheet*: every exhibit the grammar can produce,
 * laid out edge to edge on one plain, so a build can be diffed against the one
 * before it by eye. That is the right shape for spotting a regression and the
 * wrong shape for collecting an opinion. Standing in it, a reviewer sees nine
 * buildings at once, has no way to say which one the note is about, and no way
 * to get the note out of the game at all.
 *
 * The rig is the same registry — literally the same cells, read from
 * {@link planDevGrid} and {@link planPropExhibits} — rearranged around the act
 * of reviewing. Each exhibit gets a **station**: a platform floating in the
 * void with exactly one structure on it, so there is nothing else in frame to
 * confuse the judgement, and a small bank of machinery that makes the review
 * loop a thing you can do with your hands:
 *
 * - a **pressure plate** at the spot you arrive on, sitting on a command block
 *   that `say`s `>> STATION <id>`. That line lands in the client log, and it is
 *   what lets everything said afterwards be attributed to *this* exhibit;
 * - **NEXT** and **PREV** buttons that teleport to the adjacent station,
 *   wrapping at both ends, so the whole set can be walked without a map;
 * - **PASS** and **FAIL** buttons that `say VERDICT <id> pass|fail`;
 * - **signs** naming the station and its parameters, so the thing you are
 *   looking at is identified in the world and not only in a manifest.
 *
 * Nothing here talks to a model, and nothing here reads the clock: the rig is
 * generated by pure code from the pinned seed, so re-running it after a
 * grammar change produces the same stations in the same places and the
 * previous session's notes still join.
 *
 * ## Why this file writes its own chunks
 *
 * Every other world in this compiler is materialized by {@link emitTerrain},
 * which fills every column of its region from bedrock up. That is exactly
 * wrong here: the point of a station is that the exhibit stands alone against
 * sky on every side, and a shared plain is precisely the confound the rig
 * exists to remove. So the rig keeps a column plan — the generators need one,
 * and the harbour props need a pond dug into one — but materializes only the
 * columns inside a platform, and only down to {@link RIG_PLATFORM_FLOOR}.
 * Everything else is void.
 */

