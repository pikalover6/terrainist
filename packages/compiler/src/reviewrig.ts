/** The manifest for a plan — pure, so a test can build it without a world. */
export function rigManifest(plan: RigPlan, stack: PrismarineStack): RigManifest {
  const byId = stationIndex(plan);
  const entry = (s: RigStation): RigManifestStation => {
    const commands: Record<string, string> = { arrive: rigArrivalCommand(s) };
    for (const b of rigButtons(s, byId)) commands[b.label.toLowerCase()] = b.command;
    return {
      index: s.index,
      id: s.id,
      kind: s.kind,
      grid: s.grid,
      platform: s.platform,
      landing: s.landing,
      ...(s.structure === undefined ? {} : { structure: s.structure }),
      next: s.next,
      prev: s.prev,
      commands,
      provenance: s.provenance,
    };
  };
  return {
    format: "terrainist-review-rig/1",
    world: RIG_WORLD_NAME,
    minecraftVersion: stack.minecraftVersion,
    dataVersion: stack.dataVersion,
    worldSeed: RIG_WORLD_SEED.toString(),
    groundY: RIG_GROUND_Y,
    gameRules: RIG_GAME_RULES,
    stationCount: plan.stations.length,
    spawn: entry(plan.spawn),
    stations: plan.stations.map(entry),
  };
}

/** Every station by id, spawn included. */
export function stationIndex(plan: RigPlan): Map<string, RigStation> {
  const byId = new Map<string, RigStation>();
  byId.set(plan.spawn.id, plan.spawn);
  for (const s of plan.stations) byId.set(s.id, s);
  return byId;
}

/**
 * Build the rig and write it into `outDir/review_rig`, with its manifest
 * alongside.
 */
export async function buildReviewRig(outDir: string): Promise<RigResult> {
  const stack = loadPrismarine(EMIT_MINECRAFT_VERSION);
  const plan = planReviewRig();
  const byId = stationIndex(plan);
  const cells = rigCells();

  // The column plan is a *substrate*, not the world: the generators sample it
  // for ground level and material, the pond digger writes into it, and only
  // the columns inside a platform are ever materialized.
  const columnPlan = devColumnPlan(
    { x0: plan.region.x0, z0: plan.region.z0, width: plan.region.width, depth: plan.region.depth },
    stack,
  );

  // --- ponds, before anything stands on them -------------------------------
  // A harbour prop only exists over water, and the placer measures itself
  // against the finished plan, so every basin is dug first. The basin is the
  // station's structure rect grown by the margin, which keeps it clear of the
  // platform edge and so of the machinery.
  const waterRows = new Set(["harbour"]);
  let pondColumns = 0;
  for (const station of plan.stations) {
    if (station.kind !== "prop" || !waterRows.has(station.provenance.row)) continue;
    const r = station.structure as RigRect;
    pondColumns += digPropPond(
      columnPlan,
      { x0: r.x0 - 2, z0: r.z0 - 2, x1: r.x1 + 2, z1: r.z1 + 2 },
      stack,
    );
  }

  // --- the exhibits --------------------------------------------------------
  const buildingJobs: BuildingJob[] = [];
  const propJobs: PropJob[] = [];
  for (const [i, cell] of cells.entries()) {
    const station = plan.stations[i] as RigStation;
    const rect = station.structure as RigRect;
    const nodePath = cell.provenance.nodePath;
    if (cell.kind === "building") {
      const e = cell.exhibit as DevExhibit;
      const seed = nodeSeed(RIG_WORLD_SEED, nodePath, e.seedSalt ?? "");
      const theme = pickTheme(seed, e.theme);
      const materials = assignMaterials(theme, 1, seed)[0] as BuildingMaterials;
      buildingJobs.push({
        nodePath,
        placement: {
          nodePath,
          id: station.id,
          translation: [rect.x0, RIG_GROUND_Y, rect.z0] as [number, number, number],
          yaw: 0,
          mirror: false,
          size: e.size,
          footprint: { x0: rect.x0, z0: rect.z0, x1: rect.x1, z1: rect.z1 },
          anchor: { x: rect.x0 + ((e.size[0] - 1) >> 1), z: rect.z0 + ((e.size[2] - 1) >> 1) },
          foundationY: RIG_GROUND_Y,
        },
        size: e.size,
        params: exhibitParams(e),
        ports: RIG_PORTS,
        seed,
        tags: [e.archetype],
        materials,
      });
    } else {
      const p = cell.prop as PropExhibit;
      const seed = nodeSeed(RIG_WORLD_SEED, nodePath, "");
      const theme = pickTheme(seed, p.theme);
      const materials = assignMaterials(theme, 1, seed)[0] as BuildingMaterials;
      propJobs.push({
        nodePath,
        prop: p.prop,
        params: { ...p.params, at: { x: rect.x0, z: rect.z0 } },
        seed,
        materials,
      });
    }
  }

  const built = buildBuildings(buildingJobs, columnPlan, stack);
  const props = buildProps({ jobs: propJobs, plan: columnPlan, stack });

  // --- the machinery -------------------------------------------------------
  const machineryBlocks: StructureBlock[] = [];
  const entities: BlockEntity[] = [];
  for (const station of [plan.spawn, ...plan.stations]) {
    const m = buildMachinery(station, rigButtons(station, byId), stack);
    machineryBlocks.push(...m.blocks);
    entities.push(...m.entities);
  }

  // --- materialize ---------------------------------------------------------
  const structureBlocks = [...built.blocks, ...props.blocks, ...machineryBlocks];
  const chunks = new Map<string, EmitChunk>();
  const chunkFor = (cx: number, cz: number): EmitChunk => {
    const key = `${cx},${cz}`;
    let chunk = chunks.get(key);
    if (chunk === undefined) {
      chunk = stack.createChunk();
      paintChunkBiome(chunk, columnPlan.biome[0] as number);
      chunks.set(key, chunk);
    }
    return chunk;
  };

  let blockCount = 0;
  for (const station of [plan.spawn, ...plan.stations]) {
    blockCount += materializePlatform(chunkFor, columnPlan, station.platform);
  }
  for (const block of structureBlocks) {
    if (block.y < WORLD_MIN_Y || block.y > 319) continue;
    const cx = block.x >> 4;
    const cz = block.z >> 4;
    chunkFor(cx, cz).setStateId(block.x - cx * 16, block.y, block.z - cz * 16, block.stateId);
    blockCount++;
  }
  for (const entity of entities) {
    const cx = entity.x >> 4;
    const cz = entity.z >> 4;
    chunkFor(cx, cz).setBlockEntityNbt(entity.x, entity.y, entity.z, {
      ...entity.data,
      id: { type: "string", value: entity.id },
    });
  }

  // Fences, walls and panes store their neighbours in their own state and the
  // game never recomputes it, so the connection pass runs over the finished
  // world exactly as it does for a compiled one.
  const connections = applyConnectionStates(chunks, structureBlocks, stack);

  const worldDir = path.join(path.resolve(outDir), RIG_WORLD_NAME);
  const written = await writeWorldFiles({
    chunks,
    worldDir,
    levelName: RIG_WORLD_NAME,
    spawn: { x: plan.spawn.landing.x, y: plan.spawn.landing.y, z: plan.spawn.landing.z },
    stack,
    gameRules: RIG_GAME_RULES,
  });

  const manifest = rigManifest(plan, stack);
  const manifestPath = path.join(path.resolve(outDir), RIG_MANIFEST_NAME);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  return {
    plan,
    manifest,
    worldDir: written.worldDir,
    manifestPath,
    levelDatPath: written.levelDatPath,
    regionFiles: written.regionFiles,
    chunkCount: written.chunkCount,
    blockCount,
    pondColumns,
    blockEntityCount: entities.length,
    stationCount: plan.stations.length,
    buildings: built.built,
    placedProps: props.placed,
    structureBlocks,
    entities,
    connections,
    minecraftVersion: stack.minecraftVersion,
    dataVersion: stack.dataVersion,
  };
}

/**
 * Write one platform's columns out of the plan.
 *
 * A bounded, floored version of the terrain emitter's column fill: soil and
 * surface exactly as the plan holds them (so a dug basin arrives as sand and
 * water rather than as a hole in the grass), stone from there down to
 * {@link RIG_PLATFORM_FLOOR}, and nothing at all outside the rectangle. No
 * bedrock: the underside of a platform is meant to be *seen*, and a course of
 * bedrock under every station would read as a floor the world once had.
 */
function materializePlatform(
  chunkFor: (cx: number, cz: number) => EmitChunk,
  plan: ColumnPlan,
  rect: RigRect,
): number {
  const { region } = plan;
  const stone = plan.states.stone;
  let count = 0;
  for (let z = rect.z0; z <= rect.z1; z++) {
    const j = z - region.z0;
    if (j < 0 || j >= region.depth) continue;
    for (let x = rect.x0; x <= rect.x1; x++) {
      const i = x - region.x0;
      if (i < 0 || i >= region.width) continue;
      const idx = j * region.width + i;
      const chunk = chunkFor(x >> 4, z >> 4);
      const lx = x - (x >> 4) * 16;
      const lz = z - (z >> 4) * 16;

      const top = plan.ground[idx] as number;
      const soilDepth = plan.soil[idx] as number;
      const soilBase = top - soilDepth;
      if (soilBase - 1 >= RIG_PLATFORM_FLOOR) {
        chunk.fillColumn(lx, lz, RIG_PLATFORM_FLOOR, soilBase - 1, stone);
        count += soilBase - RIG_PLATFORM_FLOOR;
      }
      if (soilDepth > 0 && top - 1 >= soilBase) {
        chunk.fillColumn(lx, lz, soilBase, top - 1, plan.subsurface[idx] as number);
        count += top - soilBase;
      }
      chunk.setStateId(lx, top, lz, plan.surface[idx] as number);
      count += 1;

      const kind = plan.fluidKind[idx];
      if (kind !== FluidKind.NONE) {
        const fluidState = kind === FluidKind.LAVA ? plan.states.lava : plan.states.water;
        const surfaceY = plan.fluidTop[idx] as number;
        if (surfaceY > top) {
          chunk.fillColumn(lx, lz, top + 1, surfaceY, fluidState);
          count += surfaceY - top;
        }
      }
    }
  }
  return count;
}

/** Paint a whole chunk one biome, at the 4×4×4 resolution the format wants. */
function paintChunkBiome(chunk: EmitChunk, biomeId: number): void {
  for (let cellZ = 0; cellZ < 4; cellZ++) {
    for (let cellX = 0; cellX < 4; cellX++) {
      for (let y = WORLD_MIN_Y; y < WORLD_MIN_Y + 384; y += 4) {
        chunk.setBiomeAt(cellX * 4, y, cellZ * 4, biomeId);
      }
    }
  }
}
